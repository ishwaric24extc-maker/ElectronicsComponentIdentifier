public class Component {

    String name;
    String category;
    String function;
    String pins;
    String applications;
    String advantages;

    public Component(String name, String category, String function,
                     String pins, String applications, String advantages) {

        this.name = name;
        this.category = category;
        this.function = function;
        this.pins = pins;
        this.applications = applications;
        this.advantages = advantages;
    }
}